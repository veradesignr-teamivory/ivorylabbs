window.formatIvoryPrice = function formatIvoryPrice(service) {
  if (service.quoteOnly) return "Written monthly plan";
  const amount = `$${service.price.toLocaleString("en-US")}`;
  switch (service.billing) {
    case "month":
      return `From ${amount}/month`;
    case "platform":
      return `${amount}/platform`;
    case "pack":
      return `From ${amount} per 10,000 followers`;
    case "review":
      return `From ${amount}/review`;
    default:
      return `From ${amount}`;
  }
};

